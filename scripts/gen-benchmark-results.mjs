#!/usr/bin/env node
// F-DOC-10: the interceptor-chain overhead numbers in the docs are generated, never typed.
//
//   node scripts/gen-benchmark-results.mjs            write benchmarks/RESULTS.md
//   node scripts/gen-benchmark-results.mjs --check    fail when RESULTS.md is not what latest.json says
//
// benchmarks/latest.json is the source of truth (validated by benchmarks/validate_latest.py);
// the output depends on nothing else, so a release does not change it. Rerun the benchmark,
// regenerate, commit both.

import { readFileSync, writeFileSync } from 'node:fs'
import { dirname, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const repoRoot = resolve(dirname(fileURLToPath(import.meta.url)), '..')
const latestPath = 'benchmarks/latest.json'
const outputPath = 'benchmarks/RESULTS.md'

const SDK_NAMES = { python: 'Python', js: 'JavaScript', java: 'Java' }

function micros(value) {
  return value.toFixed(1)
}

function percent(value) {
  return `${value.toFixed(2)}%`
}

function runner(run) {
  const r = run.runner
  // Printed as recorded: the harnesses disagree on what osRelease means (Darwin kernel or OS version).
  const parts = [`${r.os} (release ${r.osRelease}), ${r.arch}`]
  if (r.cpuModel) parts.push(`${r.cpuModel} (${r.cpuCount} CPUs, ${r.memoryGb} GB)`)
  parts.push(`${r.runtime.name} ${r.runtime.version}`)
  if (r.ci) {
    const where = [r.ciProvider, r.ciImage].filter(Boolean).join(', ')
    parts.push(where === '' ? 'CI run' : `CI run (${where})`)
  } else {
    parts.push('local run, not CI')
  }
  return parts.join(' · ')
}

function runSection(run) {
  const name = SDK_NAMES[run.sdk] ?? run.sdk
  const lines = [
    `## ${name}`,
    '',
    `Gavio ${run.gavioVersion} · ${run.date} · seed ${run.seed} · ${run.pass ? 'pass' : '**FAIL**'}`,
    '',
    runner(run),
    '',
    '| Configuration | Stack | p50 µs | p95 µs | Overhead p50 µs | Overhead | Budget | Result |',
    '|---|---|---:|---:|---:|---:|---:|---|',
  ]
  for (const c of run.configurations) {
    const budget = c.budgetPct === null ? '—' : percent(c.budgetPct)
    lines.push(
      `| \`${c.configuration}\` | ${c.description} | ${micros(c.p50Us)} | ${micros(c.p95Us)} | ` +
        `${micros(c.overheadP50Us)} | ${percent(c.overheadPct)} | ${budget} | ${c.pass ? 'pass' : '**FAIL**'} |`,
    )
  }
  lines.push('')
  return lines
}

export function buildResults(latest) {
  const m = latest.runs[0].methodology
  const lines = [
    '# Interceptor-chain overhead results',
    '',
    `<!-- Generated by scripts/gen-benchmark-results.mjs from ${latestPath}. Do not edit; CI fails when this file is stale. -->`,
    '',
    `Source: [\`latest.json\`](./latest.json), generated ${latest.generatedAt}, overall ${latest.pass ? 'pass' : '**FAIL**'}.`,
    `Method: [\`chain-overhead/README.md\`](./chain-overhead/README.md). To reproduce or add an outside rerun, follow [\`chain-overhead/REPRODUCE.md\`](./chain-overhead/REPRODUCE.md).`,
    '',
    `Every figure is the added latency of a Gavio stack over a raw provider call that simulates ${m.simulatedDelayMs} ms. ` +
      `p50 and p95 are ${m.percentile} percentiles of ${m.iterations} ${m.interleaved ? 'interleaved ' : ''}iterations ` +
      `after ${m.warmup} warm-up iterations, over ${m.payloadCount} fixed payloads ` +
      `(\`${m.payloadDigest}\`). **Budget** is the most p50 overhead the stack may add, as a share of the baseline.`,
    '',
    'Differences of a few tens of µs are timer noise: compare stacks by their gaps. See "Reading the numbers" in the method README.',
    '',
  ]
  for (const run of latest.runs) lines.push(...runSection(run))
  return `${lines.join('\n').replace(/\n{3,}/g, '\n\n').trimEnd()}\n`
}

function main() {
  const latest = JSON.parse(readFileSync(resolve(repoRoot, latestPath), 'utf8'))
  const output = buildResults(latest)
  const file = resolve(repoRoot, outputPath)
  if (process.argv.includes('--check')) {
    let current = ''
    try {
      current = readFileSync(file, 'utf8')
    } catch {
      // missing counts as stale
    }
    if (current !== output) {
      console.error(`${outputPath} is out of date. Run: node scripts/gen-benchmark-results.mjs`)
      process.exit(1)
    }
    console.log(`${outputPath} matches ${latestPath}.`)
  } else {
    writeFileSync(file, output)
    console.log(`wrote ${outputPath}`)
  }
}

if (process.argv[1] !== undefined && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  main()
}
